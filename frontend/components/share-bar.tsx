async function copyToClipboard(value: string): Promise<boolean> {
  try {
    if (typeof navigator !== "undefined" && navigator.clipboard?.writeText) {
      await navigator.clipboard.writeText(value);
      return true;
    }
  } catch {
    // Fällt unten auf die execCommand-Variante zurück.
  }
  try {
    const el = document.createElement("textarea");
    el.value = value;
    el.setAttribute("readonly", "");
    el.style.position = "absolute";
    el.style.left = "-9999px";
    document.body.appendChild(el);
    el.select();
    const ok = document.execCommand("copy");
    document.body.removeChild(el);
    return ok;
  } catch {
    return false;
  }
}

export function ShareBar({ url, title, text }: Props) {
  const [copied, setCopied] = useState(false);
  const [canNativeShare, setCanNativeShare] = useState(false);

  useEffect(() => {
    setCanNativeShare(
      typeof navigator !== "undefined" && typeof navigator.share === "function",
    );
  }, []);

  const targets = buildShareTargets({ url, title, text });

  async function handleCopy() {
    const ok = await copyToClipboard(url);
    if (ok) {
      setCopied(true);
      window.setTimeout(() => setCopied(false), 2500);
    }
  }

  async function handleNativeShare() {
    try {
      await navigator.share({ title, text, url });
    } catch {
      // Vom Nutzer abgebrochen oder nicht unterstützt; kein Fehlerzustand nötig.
    }
  }

  return (
    <div className="share">
      <div className="share__actions">
        <button
          type="button"
          className={`share__btn${copied ? " share__btn--ok" : ""}`}
          onClick={handleCopy}
          aria-label={copied ? "Link kopiert" : "Link kopieren"}
        >
          {copied ? <CheckIcon /> : <LinkIcon />}
          <span>{copied ? "Link kopiert" : "Link kopieren"}</span>
        </button>

        {canNativeShare && (
          <button
            type="button"
            className="share__btn"
            onClick={handleNativeShare}
            aria-label="Über das Gerät teilen"
          >
            <ShareIcon />
            <span>Teilen</span>
          </button>
        )}
      </div>

      <ul className="share__targets">
        {targets.map((target) => (
          <li key={target.key}>
            <a
              className="share__target"
              href={target.href}
              target="_blank"
              rel="noopener noreferrer"
              aria-label={target.label}
            >
              <span className="share__icon">{BRAND_ICONS[target.key]}</span>
              <span className="share__target-name">{target.name}</span>
            </a>
          </li>
        ))}
      </ul>

      <p className="share__status" role="status" aria-live="polite">
        {copied ? "Link in die Zwischenablage kopiert." : ""}
      </p>
    </div>
  );
}
